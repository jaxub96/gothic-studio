"""
teach_gen.py - the teaching dialog for an NPC that is a teacher.

Whatever is ticked on the Talents tab, the NPC teaches. One permanent info per
group with something ticked; it offers those skills the hero has not learned
yet, each with its learning-point cost, and the choice calls the matching
B_TeachPlayerTalent* function from the Gothic II scripts.

No Qt in here.
"""

import npc_gen
import talents


def filename(npc):
    return f"DIA_{npc_gen.instance_name(npc)}_Teach.d"


def build_teaching(npc):
    """The DIA file text, or "" when no group is ticked."""
    groups = []
    for title in talents.group_titles():
        items = [i for i in talents.teachable(title) if i["id"] in npc.talents]
        if items:
            groups.append((title, items))
    if not groups:
        return ""

    inst = npc_gen.instance_name(npc)
    safe = npc_gen.sanitize(inst)
    out = [f"// Teaching dialog for {npc.name or inst} ({inst})",
           "// Generated by Gothic Studio", ""]

    for n, (title, items) in enumerate(groups):
        base = f"DIA_{safe}_Teach_{npc_gen.sanitize(title)}"
        rule = "// " + "=" * 60
        out += [rule, f"// \t\t\tTeacher: {title}", rule,
                f"INSTANCE {base} (C_INFO)", "{",
                f"\tnpc\t\t\t= {inst};",
                f"\tnr\t\t\t= {800 + n};",
                f"\tcondition\t= {base}_Condition;",
                f"\tinformation\t= {base}_Info;",
                "\tpermanent\t= TRUE;",
                f'\tdescription\t= "Teach me: {title}";',
                "};", "",
                f"FUNC INT {base}_Condition()", "{", "\treturn TRUE;", "};", "",
                f"FUNC VOID {base}_Info()", "{",
                f"\tInfo_ClearChoices\t({base});",
                f"\tInfo_AddChoice\t\t({base}, DIALOG_BACK, {base}_BACK);"]
        for item in items:
            fn = f"{base}_{npc_gen.sanitize(item['const'])}"
            out += [f"\tif ({item['unknown']})", "\t{",
                    f"\t\tInfo_AddChoice\t({base}, B_BuildLearnString "
                    f"(\"{item['label']}\", {item['cost']}), {fn});",
                    "\t};"]
        out += ["};", "",
                f"FUNC VOID {base}_BACK()", "{",
                f"\tInfo_ClearChoices\t({base});", "};", ""]
        for item in items:
            fn = f"{base}_{npc_gen.sanitize(item['const'])}"
            out += [f"FUNC VOID {fn}()", "{",
                    f"\t{item['call']};",
                    f"\tInfo_ClearChoices\t({base});", "};", ""]
    return "\n".join(out)


def parse_teaching(text):
    """Talent ids a teaching file offers: the inverse of build_teaching()."""
    import re

    consts = set(re.findall(
        r"B_Teach(?:PlayerTalent\w+|ThiefTalent)\s*\(\s*self\s*,\s*other\s*,\s*(\w+)\s*\)", text))
    return {item["id"] for title in talents.group_titles()
            for item in talents.teachable(title) if item["const"] in consts}
